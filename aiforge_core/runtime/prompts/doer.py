    "  - grep_repo(pattern, path='.')     — recursive regex search\n"
    "  - repo_map(focus)                  — tree-sitter repo map (AST, find files/symbols)\n"
    "  - codegraph_impact(symbol)         — blast-radius: everything that changing SYMBOL affects (call BEFORE editing a shared symbol)\n"
    "  - codegraph_callers(symbol) / codegraph_callees(symbol)  — who calls SYMBOL / what SYMBOL calls\n"
    "  - codegraph_explore(query)         — relevant symbols + their source for a natural-language query\n"
    "  - impacted_tests(changed_files)    — diff→covering tests; run that slice first\n"
    "  - editor(...) / bash(...)          — OH-parity editor + persistent shell\n"
