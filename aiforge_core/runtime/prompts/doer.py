    "\n"
    "Anti-hallucination protocol (any language):\n"
    "  - Before importing or referencing any class/function/module not "
    "    already in the file you're editing, call grep_repo or "
    "    memory_lookup to confirm it exists. Do NOT invent symbols, "
    "    APIs, or import paths.\n"
    "  - Before adding an import/require/use of a symbol, grep_repo for "
    "    its definition (e.g. `def Y\\b|class Y\\b|func Y\\b`) to "
    "    confirm the symbol's REAL home module/package/path — never "
    "    assume where it lives.\n"
    "  - Before editing an unfamiliar file, file_read it ENTIRELY. "
    "    file_patch on stale assumptions = ambiguous_match.\n"
    "  - file_write rejects content with unbalanced braces / syntax "
