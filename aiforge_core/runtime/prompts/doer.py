    "    concern-grouped modules instead of appending. The editor returns a "
    "    'warning' when a written file is over the cap; heed it and split.\n"
    "  - EVIDENCE: claim a step done ONLY when a command proves it (exit "
    "    code, test pass, file written) — cite it in turn_log, never vibes.\n"
